package Strings;

public class ConcatenationInString {
    public static void main(String[] args){
        String str = "Anshuman Singh";
        str+=10;
        System.out.println(str);

        String gtr = "Amit Singh";
        gtr+='A';
        System.out.println(gtr);

        String ftr = "ABCD";
        ftr+="EFGH";
        System.out.println(ftr);
    }
}
